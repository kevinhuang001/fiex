import { chromium } from '@playwright/test'
const b = await chromium.launch(); const p = await b.newPage({ viewport:{width:1200,height:900} })
await p.goto('http://127.0.0.1:1420/?officialPlugins'); await p.waitForTimeout(900)
await p.evaluate(() => window.dispatchEvent(new CustomEvent('fiex:plugin-panel:open', { detail: { pluginId: 'org.fiex.git', panelId: 'git.main', title: '源代码管理', selection: [], directory: '/Users/kevin/Documents', icon: 'git-branch', size: { width: 560, height: 620 } } })))
await p.waitForTimeout(1500)
const frame = p.frameLocator('iframe[title="源代码管理"]')
await frame.getByRole('button', { name: /暂存全部/ }).click()
await p.waitForTimeout(700)
await frame.getByRole('button', { name: /提交修改/ }).click()
await p.waitForTimeout(500)
await p.screenshot({ path: '/tmp/gitcommit.png' })
await b.close()
